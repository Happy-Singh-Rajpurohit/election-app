-- 1. DDL Statements (Data Definition Language)
-- Creating tables up to 3NF/BCNF with constraints

CREATE TABLE Election (
    election_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR2(20) NOT NULL CHECK(status IN ('Upcoming', 'Ongoing', 'Completed'))
);

CREATE TABLE Constituency (
    constituency_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE Voter (
    voter_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    constituency_id NUMBER NOT NULL,
    approval_status VARCHAR2(20) DEFAULT 'Pending' CHECK(approval_status IN ('Pending', 'Approved', 'Rejected')),
    CONSTRAINT fk_voter_constituency FOREIGN KEY (constituency_id) REFERENCES Constituency(constituency_id)
);

CREATE TABLE PoliticalParty (
    party_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE Candidate (
    candidate_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    party_id NUMBER NOT NULL,
    election_id NUMBER NOT NULL,
    constituency_id NUMBER NOT NULL,
    approval_status VARCHAR2(20) DEFAULT 'Pending' CHECK(approval_status IN ('Pending', 'Approved', 'Rejected')),
    CONSTRAINT fk_candidate_party FOREIGN KEY (party_id) REFERENCES PoliticalParty(party_id),
    CONSTRAINT fk_candidate_election FOREIGN KEY (election_id) REFERENCES Election(election_id),
    CONSTRAINT fk_candidate_constituency FOREIGN KEY (constituency_id) REFERENCES Constituency(constituency_id)
);

CREATE TABLE Vote (
    vote_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voter_id NUMBER NOT NULL,
    candidate_id NUMBER NOT NULL,
    election_id NUMBER NOT NULL,
    vote_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_vote_voter FOREIGN KEY (voter_id) REFERENCES Voter(voter_id),
    CONSTRAINT fk_vote_candidate FOREIGN KEY (candidate_id) REFERENCES Candidate(candidate_id),
    CONSTRAINT fk_vote_election FOREIGN KEY (election_id) REFERENCES Election(election_id),
    CONSTRAINT uq_vote_per_election UNIQUE (voter_id, election_id) -- Ensures one vote per voter per election
);

CREATE TABLE ElectionOfficer (
    officer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    role VARCHAR2(50) NOT NULL
);

CREATE TABLE AuditLog (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    action VARCHAR2(255) NOT NULL,
    log_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

