-- Trigger to Automatically Insert Audit Log on Vote
CREATE OR REPLACE TRIGGER trg_audit_vote
AFTER INSERT ON Vote
FOR EACH ROW
BEGIN
    INSERT INTO AuditLog (user_id, action)
    VALUES (:NEW.voter_id, 'Casted vote for candidate ' || :NEW.candidate_id || ' in election ' || :NEW.election_id);
END;
/

-- Procedure to Cast Vote with Exception Handling & Transaction Management
CREATE OR REPLACE PROCEDURE cast_vote (
    p_voter_id NUMBER,
    p_candidate_id NUMBER,
    p_election_id NUMBER
) AS
    v_count NUMBER;
BEGIN
    -- Check if voter has already voted
    SELECT COUNT(*) INTO v_count FROM Vote WHERE voter_id = p_voter_id AND election_id = p_election_id;
    
    IF v_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Voter has already cast a vote in this election.');
    END IF;

    -- Insert vote
    INSERT INTO Vote (voter_id, candidate_id, election_id)
    VALUES (p_voter_id, p_candidate_id, p_election_id);

    COMMIT; -- Success, commit transaction
    DBMS_OUTPUT.PUT_LINE('Vote cast successfully!');

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK; -- If validation or insertion fails
        DBMS_OUTPUT.PUT_LINE('Error casting vote: ' || SQLERRM);
END;
/

-- Function to Calculate Vote Percentage for a Candidate
CREATE OR REPLACE FUNCTION get_vote_percentage(
    p_candidate_id NUMBER, 
    p_election_id NUMBER
) RETURN NUMBER IS
    t_votes NUMBER := 0;
    c_votes NUMBER := 0;
    v_percentage NUMBER := 0;
BEGIN
    SELECT COUNT(*) INTO t_votes FROM Vote WHERE election_id = p_election_id;
    SELECT COUNT(*) INTO c_votes FROM Vote WHERE candidate_id = p_candidate_id AND election_id = p_election_id;
    
    IF t_votes > 0 THEN
        v_percentage := (c_votes / t_votes) * 100;
    END IF;
    
    RETURN v_percentage;
END;
/

-- Cursor to Display Election Results
CREATE OR REPLACE PROCEDURE declare_results (p_election_id NUMBER) AS
    CURSOR c_results IS
        SELECT c.name, p.party_name, COUNT(v.vote_id) AS total_votes
        FROM Candidate c
        LEFT JOIN Vote v ON c.candidate_id = v.candidate_id
        JOIN PoliticalParty p ON c.party_id = p.party_id
        WHERE c.election_id = p_election_id
        GROUP BY c.name, p.party_name
        ORDER BY total_votes DESC;
BEGIN
    DBMS_OUTPUT.PUT_LINE('-------------------------------------------');
    DBMS_OUTPUT.PUT_LINE('ELECTION RESULTS');
    DBMS_OUTPUT.PUT_LINE('-------------------------------------------');
    
    FOR r IN c_results LOOP
        DBMS_OUTPUT.PUT_LINE('Candidate: ' || r.name || ' | Party: ' || r.party_name || ' | Votes: ' || r.total_votes);
        DBMS_OUTPUT.PUT_LINE('Vote Share: ' || ROUND(get_vote_percentage(r.name, p_election_id), 2) || '%'); -- Assuming overloaded function or logic rewrite
    END LOOP;
END;
/

